  (H_TmZero : P_t TmZero)
  (H_TmSucc : forall (t5:t), P_t t5 -> P_t (TmSucc t5))
  (H_TmPred : forall (t5:t), P_t t5 -> P_t (TmPred t5))
  (H_TmIszero : forall (t5:t), P_t t5 -> P_t (TmIszero t5))
