Section T_rect.

Variables
  (P_T : T -> Prop)
  (P_list_T : list T -> Prop)
  (P_list_label_T : list (label*T) -> Prop).

Hypothesis
  (H_TyBool : P_T TyBool)
  (H_TyNat : P_T TyNat)
  (H_TyArr : forall (T5:T), P_T T5 -> forall (T':T), P_T T' -> P_T (TyArr T5 T'))
  (H_TyId : forall (A:basetype), P_T (TyId A))
  (H_TyUnit : P_T TyUnit)
  (H_TyPair : forall (T1:T), P_T T1 -> forall (T2:T), P_T T2 -> P_T (TyPair T1 T2))
  (H_TySum : forall (T1:T), P_T T1 -> forall (T2:T), P_T T2 -> P_T (TySum T1 T2))
  (H_TyTuple : forall (T_list:list T), P_list_T T_list -> P_T (TyTuple T_list))
  (H_TyVariant : forall (l_T_list:list (label*T)), P_list_label_T l_T_list -> P_T (TyVariant l_T_list))
  (H_list_T_nil : P_list_T nil)
  (H_list_T_cons : forall (T0:T), P_T T0 -> forall (T_l:list T), P_list_T T_l -> P_list_T (cons T0 T_l))
  (H_list_label_T_nil : P_list_label_T nil)
  (H_list_label_T_cons : forall (label0:label), forall (T1:T), P_T T1 -> forall (label_T_l:list (label*T)), P_list_label_T label_T_l -> P_list_label_T (cons (label0,T1) label_T_l)).

Fixpoint T_ott_ind (n:T) : P_T n :=
  match n as x return P_T x with
  | TyBool => H_TyBool 
  | TyNat => H_TyNat 
  | (TyArr T5 T') => H_TyArr T5 (T_ott_ind T5) T' (T_ott_ind T')
  | (TyId A) => H_TyId A
  | TyUnit => H_TyUnit 
  | (TyPair T1 T2) => H_TyPair T1 (T_ott_ind T1) T2 (T_ott_ind T2)
  | (TySum T1 T2) => H_TySum T1 (T_ott_ind T1) T2 (T_ott_ind T2)
  | (TyTuple T_list) => H_TyTuple T_list (((fix T_list_ott_ind (T_l:list T) : P_list_T T_l := match T_l as x return P_list_T x with nil => H_list_T_nil | cons T2 xl => H_list_T_cons T2(T_ott_ind T2)xl (T_list_ott_ind xl) end)) T_list)
  | (TyVariant l_T_list) => H_TyVariant l_T_list (((fix l_T_list_ott_ind (label_T_l:list (label*T)) : P_list_label_T label_T_l := match label_T_l as x return P_list_label_T x with nil => H_list_label_T_nil | cons (label1,T3) xl => H_list_label_T_cons label1  T3(T_ott_ind T3)xl (l_T_list_ott_ind xl) end)) l_T_list)
end.

End T_rect.


