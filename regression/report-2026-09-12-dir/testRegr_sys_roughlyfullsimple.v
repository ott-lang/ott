  match n as x return P_t x with
  | TmTrue => H_TmTrue 
  | TmFalse => H_TmFalse 
  | (TmIf t1 t2 t3) => H_TmIf t1 (t_ott_ind t1) t2 (t_ott_ind t2) t3 (t_ott_ind t3)
  | TmZero => H_TmZero 
  | (TmSucc t5) => H_TmSucc t5 (t_ott_ind t5)
  | (TmPred t5) => H_TmPred t5 (t_ott_ind t5)
  | (TmIszero t5) => H_TmIszero t5 (t_ott_ind t5)
  | (TmVar x) => H_TmVar x
  | (TmAbs x T5 t5) => H_TmAbs x T5 t5 (t_ott_ind t5)
  | (TmApp t1 t2) => H_TmApp t1 (t_ott_ind t1) t2 (t_ott_ind t2)
  | TmUnit => H_TmUnit 
  | (TmSeq t1 t2) => H_TmSeq t1 (t_ott_ind t1) t2 (t_ott_ind t2)
